-- =====================================================================
-- Sistema de Foros en Línea - Paso 1: tablas y datos de prueba
-- ---------------------------------------------------------------------
-- Ejecutar como ADMIN en Database Actions > SQL (botón "Run Script"),
-- después de 00_crear_usuario_app.sql.
--
-- Las tablas se crean en el esquema FORO_APP (no en ADMIN).
-- El script se puede volver a ejecutar: borra y recrea todo.
--
-- Convención de nombres (una sola base, dos microservicios):
--   USR_*  -> tablas del microservicio de usuarios
--   FOR_*  -> tablas del microservicio de foro
--
-- La aplicación nunca borra registros: los desactiva.
--   Usuarios            -> ACTIVO = 0
--   Temas y comentarios -> ESTADO = 'ELIMINADO'
-- =====================================================================

ALTER SESSION SET CURRENT_SCHEMA = FORO_APP;

-- ---------------------------------------------------------------------
-- 1. Limpieza (permite re-ejecutar el script)
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT TABLE_NAME
                FROM ALL_TABLES
               WHERE OWNER = 'FORO_APP'
                 AND TABLE_NAME IN ('FOR_COMENTARIO', 'FOR_TEMA', 'FOR_CATEGORIA',
                                    'USR_USUARIO', 'USR_ROL')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE FORO_APP.' || t.TABLE_NAME
                          || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 2. Tablas
-- ---------------------------------------------------------------------

-- Catálogo de roles (solo lectura para la aplicación).
--   USUARIO -> publica y comenta; edita y elimina solo lo suyo.
--   ADMIN   -> además administra usuarios y puede eliminar temas y
--              comentarios de cualquiera.
CREATE TABLE USR_ROL (
    ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE       VARCHAR2(20)  NOT NULL,
    DESCRIPCION  VARCHAR2(255) NOT NULL,
    CONSTRAINT USR_ROL_PK         PRIMARY KEY (ID),
    CONSTRAINT USR_ROL_NOMBRE_UK  UNIQUE (NOMBRE)
);

-- Usuarios del foro. ACTIVO = 0 significa deshabilitado: no puede
-- iniciar sesión, pero sus temas y comentarios se conservan.
CREATE TABLE USR_USUARIO (
    ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_USUARIO   VARCHAR2(50)  NOT NULL,
    EMAIL            VARCHAR2(120) NOT NULL,
    PASSWORD_HASH    VARCHAR2(100) NOT NULL,
    NOMBRE_COMPLETO  VARCHAR2(100) NOT NULL,
    ROL_ID           NUMBER        NOT NULL,
    ACTIVO           NUMBER(1)     DEFAULT 1 NOT NULL,
    FECHA_REGISTRO   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT USR_USUARIO_PK         PRIMARY KEY (ID),
    CONSTRAINT USR_USUARIO_NOMBRE_UK  UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT USR_USUARIO_EMAIL_UK   UNIQUE (EMAIL),
    CONSTRAINT USR_USUARIO_ROL_FK     FOREIGN KEY (ROL_ID) REFERENCES USR_ROL (ID),
    CONSTRAINT USR_USUARIO_ACTIVO_CK  CHECK (ACTIVO IN (0, 1))
);

-- Catálogo de categorías de temas (solo lectura para la aplicación).
CREATE TABLE FOR_CATEGORIA (
    ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE       VARCHAR2(60)  NOT NULL,
    DESCRIPCION  VARCHAR2(255) NOT NULL,
    CONSTRAINT FOR_CATEGORIA_PK         PRIMARY KEY (ID),
    CONSTRAINT FOR_CATEGORIA_NOMBRE_UK  UNIQUE (NOMBRE)
);

-- Temas publicados por los usuarios.
-- ESTADO: ACTIVO (visible), ELIMINADO (borrado por su autor o un admin)
-- o BANEADO (reservado para un futuro microservicio de moderación).
CREATE TABLE FOR_TEMA (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TITULO              VARCHAR2(150)  NOT NULL,
    CONTENIDO           VARCHAR2(4000) NOT NULL,
    CATEGORIA_ID        NUMBER         NOT NULL,
    AUTOR_ID            NUMBER         NOT NULL,
    ESTADO              VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_MODIFICACION  TIMESTAMP,
    CONSTRAINT FOR_TEMA_PK            PRIMARY KEY (ID),
    CONSTRAINT FOR_TEMA_CATEGORIA_FK  FOREIGN KEY (CATEGORIA_ID) REFERENCES FOR_CATEGORIA (ID),
    CONSTRAINT FOR_TEMA_AUTOR_FK      FOREIGN KEY (AUTOR_ID)     REFERENCES USR_USUARIO (ID),
    CONSTRAINT FOR_TEMA_ESTADO_CK     CHECK (ESTADO IN ('ACTIVO', 'ELIMINADO', 'BANEADO'))
);

-- Comentarios de cada tema. Mismos estados que los temas.
CREATE TABLE FOR_COMENTARIO (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TEMA_ID             NUMBER         NOT NULL,
    AUTOR_ID            NUMBER         NOT NULL,
    CONTENIDO           VARCHAR2(2000) NOT NULL,
    ESTADO              VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_MODIFICACION  TIMESTAMP,
    CONSTRAINT FOR_COMENTARIO_PK         PRIMARY KEY (ID),
    CONSTRAINT FOR_COMENTARIO_TEMA_FK    FOREIGN KEY (TEMA_ID)  REFERENCES FOR_TEMA (ID),
    CONSTRAINT FOR_COMENTARIO_AUTOR_FK   FOREIGN KEY (AUTOR_ID) REFERENCES USR_USUARIO (ID),
    CONSTRAINT FOR_COMENTARIO_ESTADO_CK  CHECK (ESTADO IN ('ACTIVO', 'ELIMINADO', 'BANEADO'))
);

-- Índices para las búsquedas por llave foránea.
CREATE INDEX USR_USUARIO_ROL_IX        ON USR_USUARIO (ROL_ID);
CREATE INDEX FOR_TEMA_CATEGORIA_IX     ON FOR_TEMA (CATEGORIA_ID);
CREATE INDEX FOR_TEMA_AUTOR_IX         ON FOR_TEMA (AUTOR_ID);
CREATE INDEX FOR_COMENTARIO_TEMA_IX    ON FOR_COMENTARIO (TEMA_ID);
CREATE INDEX FOR_COMENTARIO_AUTOR_IX   ON FOR_COMENTARIO (AUTOR_ID);

